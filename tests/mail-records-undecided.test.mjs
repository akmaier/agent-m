import test from "node:test";
import assert from "node:assert/strict";
import * as records from "../src/mail-records/index.mjs";
import { sha256 } from "../src/text-tools/index.mjs";

// Only the missing intended function is optional; broken entry or transitive imports still fail to load.
// All inputs and expected identifiers are synthetic literals, not generated by the implementation.

// TST-644001
// level: unit
// module: MOD-mail-records
// guards: A MAIL ALREADY DECIDED IS NOT PROPOSED AGAIN; UC-038
// given: public hash and mailId controls work; one identifier is issue-listed, another browser-marked, a third undecided
// input: ids [MAIL-1111111111111111, MAIL-2222222222222222, MAIL-3333333333333333]; listed {MAIL-1111111111111111}; marked {MAIL-2222222222222222}
// expect: synchronously [MAIL-3333333333333333]; all inputs unchanged; no network request or browser-setting access
test("TST-644001 mixed decisions leave only the unlisted and unmarked identifier", async (t) => {
  assert.equal(await sha256("abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
  assert.equal(await records.mailId({ messageId: "<abc>", bytes: null }), "MAIL-ba7816bf8f01cfea");
  t.diagnostic("Known-positive public sha256 and existing mailId controls passed before undecided.");
  const accesses = [];
  const fetch = globalThis.fetch;
  const storage = Object.getOwnPropertyDescriptor(globalThis, "localStorage");
  t.after(() => {
    globalThis.fetch = fetch;
    if (storage) Object.defineProperty(globalThis, "localStorage", storage);
    else delete globalThis.localStorage;
  });
  globalThis.fetch = (...args) => { accesses.push(["fetch", ...args]); throw new Error("No network in undecided"); };
  Object.defineProperty(globalThis, "localStorage", { configurable: true, get() {
    accesses.push("localStorage");
    throw new Error("No browser settings in undecided");
  } });
  const ids = ["MAIL-1111111111111111", "MAIL-2222222222222222", "MAIL-3333333333333333"];
  const listed = new Set(["MAIL-1111111111111111"]);
  const marked = new Set(["MAIL-2222222222222222"]);
  assert.deepEqual(records.undecided?.(ids, listed, marked), ["MAIL-3333333333333333"]);
  assert.deepEqual(ids, ["MAIL-1111111111111111", "MAIL-2222222222222222", "MAIL-3333333333333333"]);
  assert.deepEqual(listed, new Set(["MAIL-1111111111111111"]));
  assert.deepEqual(marked, new Set(["MAIL-2222222222222222"]));
  assert.deepEqual(accesses, []);
});

